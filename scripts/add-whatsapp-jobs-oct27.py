from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "add_direct", ROOT / "scripts" / "add-direct-jobs-oct09.py"
)
direct_mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(direct_mod)

mod = direct_mod.mod


def job(*args, benefits: list[str] | None = None, qualification: str = "", website: str = "", source: str = "WhatsApp", **kw) -> dict:
    """direct() without its generic filler: empty fields stay empty unless the poster states them."""
    kw.setdefault("requirements", [])
    item = direct_mod.direct(*args, **kw)
    item["id"] = item["id"].replace("-oct26", "-oct27")
    item["postedDate"] = "2026-10-27"
    item["responsibilities"] = kw.get("responsibilities") or []
    item["benefits"] = benefits or []
    item["qualification"] = qualification
    item["website"] = website
    item["source"] = source
    item["industry"] = ""
    item["workMode"] = kw.get("work_mode", "")
    item["companyBlurb"] = " · ".join(x for x in (item["company"], args[2], args[3]) if x)
    return item


