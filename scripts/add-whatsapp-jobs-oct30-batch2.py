from __future__ import annotations

import importlib.util
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("posters30", ROOT / "scripts" / "add-whatsapp-jobs-oct30.py")
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)
mod = base.mod

NOT_PRINTED = "Location not printed on the notice"


def job(slug, company, title, location, *, recruiter: bool = False, **kw) -> dict:
    kw.setdefault("experience", "experienced")
    kw.setdefault("experience_range", "")
    kw.setdefault("tags", [])
    kw.setdefault("work_details", "")
    email = kw.get("email", "")
    phone = kw.get("phone", "")
    if not kw.get("apply_link"):
        if email:
            kw["apply_link"] = f"mailto:{email}?subject={quote(title)}"
        elif phone:
            kw["apply_link"] = "tel:+91" + "".join(ch for ch in phone if ch.isdigit())[-10:]
    item = base.job(slug, company, title, location, **kw)
    if location == NOT_PRINTED and not kw.get("address"):
        item["address"] = ""
    if recruiter:
        item["hiringNotes"] = "Added 30 Oct 2026 from the recruiter's post. Verify with the recruiter before applying."
    return item


def hirestar(slug, title, location, *, email, phone, **kw) -> dict:
    return job(
        slug,
        "Hirestar Global (client not named)",
        title,
        location,
        email=email,
        phone=phone,
        recruiter=True,
        how=f"Forward your updated resume to {email} or contact {phone}.",
        **kw,
    )


