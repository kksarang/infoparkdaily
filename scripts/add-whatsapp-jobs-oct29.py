from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "add_direct", ROOT / "scripts" / "add-direct-jobs-oct09.py"
)
direct_mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(direct_mod)

mod = direct_mod.mod


def job(
    *args,
    benefits: list[str] | None = None,
    qualification: str = "",
    website: str = "",
    source: str = "WhatsApp",
    walk_in: str = "",
    walk_in_time: str = "",
    address: str = "",
    **kw,
) -> dict:
    """direct() without its generic filler: empty fields stay empty unless the poster states them."""
    kw.setdefault("requirements", [])
    kw.setdefault("deadline", "")
    item = direct_mod.direct(*args, **kw)
    item["id"] = item["id"].replace("-oct26", "-oct29")
    item["postedDate"] = "2026-10-29"
    item["responsibilities"] = kw.get("responsibilities") or []
    item["benefits"] = benefits or []
    item["qualification"] = qualification
    item["website"] = website
    item["source"] = source
    item["industry"] = ""
    item["workMode"] = kw.get("work_mode", "")
    item["hiringNotes"] = "Added 29 Oct 2026 from the employer's hiring poster. Verify with the employer before applying."
    item["companyBlurb"] = " · ".join(x for x in (item["company"], args[2], args[3]) if x)
    if address:
        item["address"] = address
    if walk_in:
        item["isWalkIn"] = True
        item["walkInDate"] = walk_in
        if walk_in_time:
            item["walkinTime"] = walk_in_time
    return item


