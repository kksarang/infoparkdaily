#!/usr/bin/env python3
"""Data-quality and source-coverage reports for data/jobs-data.js.

Writes:
  reports/data-quality.json   machine-readable issues per job
  reports/data-quality.md     summary for humans
  reports/source-coverage.md  registry + last probe results

Usage: python3 -m pipeline.quality [--strict]
--strict exits non-zero when error-severity issues exist (for CI).
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

from pipeline import rules

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
REGISTRY = ROOT / "pipeline" / "registry.json"
RUNS = REPORTS / "source-runs.json"


def load_jobs() -> list[dict]:
    """jobs-data.js is a JS literal (unquoted keys), so let Node evaluate it."""
    script = (
        "const fs=require('fs');"
        "const J=new Function(fs.readFileSync(process.argv[1],'utf8')+';return JOBS')();"
        "process.stdout.write(JSON.stringify(J));"
    )
    out = subprocess.run(
        ["node", "-e", script, str(ROOT / "data" / "jobs-data.js")], capture_output=True, check=True
    ).stdout
    return json.loads(out)


def build_report(jobs: list[dict]) -> dict:
    today = rules.ist_today()
    statuses = Counter()
    per_job = []
    for job in jobs:
        status = rules.job_status(job, today)
        statuses[status] += 1
        issues = rules.validate_job(job, today)
        if issues:
            per_job.append({"id": job.get("id"), "company": job.get("company"), "status": status, "issues": issues})
    dups = rules.find_duplicates(jobs)
    codes = Counter((i["severity"], i["code"]) for j in per_job for i in j["issues"])
    return {
        "date_ist": today.isoformat(),
        "total_jobs": len(jobs),
        "status_counts": dict(statuses),
        "issue_counts": [{"severity": s, "code": c, "count": n} for (s, c), n in codes.most_common()],
        "duplicates": dups,
        "jobs_with_issues": per_job,
    }


def write_quality_md(report: dict) -> None:
    lines = [
        "# Jobs data quality",
        "",
        f"Checked {report['total_jobs']} jobs on {report['date_ist']} (Asia/Kolkata). Generated by `python3 -m pipeline.quality`.",
        "",
        "## Status (from published deadlines)",
        "",
        "| Status | Jobs |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in sorted(report["status_counts"].items())]
    lines += ["", "`expired` means the published deadline has passed — re-verify before calling it closed.", "", "## Issues", "", "| Severity | Code | Jobs |", "|---|---|---|"]
    lines += [f"| {i['severity']} | {i['code']} | {i['count']} |" for i in report["issue_counts"]]
    d = report["duplicates"]
    lines += [
        "",
        "## Duplicates",
        "",
        f"- Duplicate job ids: {len(d['duplicate_ids'])}",
        f"- Vacancies listed more than once (same apply URL + title, or same reference id): {len(d['duplicate_vacancies'])}",
    ]
    for key, ids in list(d["duplicate_vacancies"].items())[:25]:
        lines.append(f"  - `{key[:110]}` → {', '.join(sorted(set(ids)))[:200]}")
    (REPORTS / "data-quality.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_coverage_md() -> None:
    sources = json.loads(REGISTRY.read_text(encoding="utf-8"))["sources"]
    runs = json.loads(RUNS.read_text(encoding="utf-8")) if RUNS.exists() else {}
    lines = [
        "# Source coverage",
        "",
        "Sources configured in `pipeline/registry.json`. 'Last probe' is a reachability check only; it does not",
        "mean every vacancy at that source is on InfoparkDaily. Blocked sources are never bypassed.",
        "",
        "| Source | Category | Type | Integration | Last probe | Last success |",
        "|---|---|---|---|---|---|",
    ]
    for s in sources:
        run = runs.get(s["key"], {})
        probe = f"{run.get('result', 'never')} {run.get('http') or ''}".strip()
        lines.append(
            f"| [{s['name']}]({s['url']}) | {s['category']} | {s['type']} | {s['integration']} | {probe} | {run.get('last_success') or '—'} |"
            if s.get("url")
            else f"| {s['name']} | {s['category']} | {s['type']} | {s['integration']} | {probe} | — |"
        )
    counts = Counter(s["integration"] for s in sources)
    lines += ["", "Integration summary: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + "."]
    notes = [f"- **{s['name']}**: {s['notes']}" for s in sources if s.get("notes")]
    if notes:
        lines += ["", "## Known limitations", ""] + notes
    (REPORTS / "source-coverage.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    REPORTS.mkdir(exist_ok=True)
    report = build_report(load_jobs())
    compact = {**report, "jobs_with_issues": [
        {**j, "issues": [[i["severity"], i["code"]] for i in j["issues"] if i["severity"] != rules.INFO]}
        for j in report["jobs_with_issues"]
    ]}
    compact["jobs_with_issues"] = [j for j in compact["jobs_with_issues"] if j["issues"]]
    (REPORTS / "data-quality.json").write_text(json.dumps(compact, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    write_quality_md(report)
    write_coverage_md()
    errors = sum(i["count"] for i in report["issue_counts"] if i["severity"] == rules.ERROR)
    print(f"{report['total_jobs']} jobs · statuses {report['status_counts']} · error issues {errors}")
    return 1 if "--strict" in sys.argv and errors else 0


if __name__ == "__main__":
    sys.exit(main())
